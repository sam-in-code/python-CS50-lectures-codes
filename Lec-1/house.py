name = input("What is your name? ")

if name == "Robert" or name == "Stannis" or name == "Renly":
    print("House Baratheon")
elif name == "Eddard" or name == "Robb" or name == "Sansa":
    print ("House Stark")
elif name == "Tyrion" or name == "Jaime" or name == "Cersei":
    print("House Lannister")
else:
    print("House not found")

